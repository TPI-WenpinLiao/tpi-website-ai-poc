// Tests for scripts/wireframe/nav-fit.mjs. Run: npm run test:scripts

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fits, renderSection } from './nav-fit.mjs';

test('fits allows content up to the available width', () => {
  assert.equal(fits({ content: 1120, available: 1120 }), true);
  assert.equal(fits({ content: 1121, available: 1120 }), false);
});

test('renderSection reports margin, fit and horizontal scrolling between the markers', () => {
  const doc = renderSection({
    rows: [
      { set: 'en', font: 'Inter', labels: ['Products', 'Contact Us'], content: 1105, available: 1120 },
      { set: 'vi', font: 'Inter', labels: ['Sản Phẩm'], content: 1181, available: 1120 },
    ],
    overflow: [{ page: 'home', widths: { 375: true, 1280: false } }],
  });
  assert.match(doc, /^<!-- generated by scripts\/wireframe\/nav-fit\.mjs: start -->/);
  assert.match(doc, /<!-- generated by scripts\/wireframe\/nav-fit\.mjs: end -->$/);
  assert.match(doc, /\| `en` \| Inter \| 1105 \| 1120 \| 15 \| ✅ \|/);
  assert.match(doc, /\| `vi` \| Inter \| 1181 \| 1120 \| -61 \| ❌ \|/);
  assert.match(doc, /- `en`：Products｜Contact Us/);
  assert.match(doc, /\| `home` \| ❌ 有 \| ✅ 無 \|/);
});
