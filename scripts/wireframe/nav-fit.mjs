// Header width check for M3-01 (#14).
// Serves dist/, opens /wireframes/navigation at 1280px and measures each header row in the
// 「1280px 寬度測試」section (zh-TW, en, vi label sets, see src/lib/wireframe/header-labels.ts)
// with several fonts; also checks every wireframe page for horizontal scrolling at 375px and 1280px.
// Regenerates the marked section of docs/design/nav-fit.md.
// Run after npm run build: node scripts/wireframe/nav-fit.mjs  (--check compares without writing)
// Results depend on the installed fonts, so --check is not part of npm run check.

import { execFileSync } from 'node:child_process';
import { createReadStream, existsSync, readdirSync, statSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { extname, join, normalize } from 'node:path';
import { pathToFileURL } from 'node:url';
import puppeteer from 'puppeteer-core';
import { emit, replaceSection } from '../ia/generated.mjs';

const DIST = 'dist';
const DOC = 'docs/design/nav-fit.md';
const MARK_START = '<!-- generated by scripts/wireframe/nav-fit.mjs: start -->';
const MARK_END = '<!-- generated by scripts/wireframe/nav-fit.mjs: end -->';
const DESKTOP = 1280;
const WIDTHS = [375, DESKTOP];
// Latin fonts to measure with; CJK glyphs fall back to WenQuanYi Zen Hei in every case.
// Liberation Sans has Arial's metrics; Inter is a common UI face; DejaVu Sans is a wide worst case.
export const FONTS = ['Liberation Sans', 'Inter', 'DejaVu Sans'];
const CJK_FALLBACK = 'WenQuanYi Zen Hei';
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.svg': 'image/svg+xml' };

// A row fits when its content is no wider than the space inside the row's padding
export const fits = ({ content, available }) => content <= available;

export function renderSection({ rows, overflow }) {
  const out = [MARK_START, '', '### header 一列寬度（1280px）', ''];
  out.push('| 標籤組 | 字型 | 需要寬度 | 可用寬度 | 餘裕 | 放得下 |', '|---|---|--:|--:|--:|---|');
  for (const r of rows) {
    out.push(`| \`${r.set}\` | ${r.font} | ${r.content} | ${r.available} | ${r.available - r.content} | ${fits(r) ? '✅' : '❌'} |`);
  }
  out.push('', '寬度單位為 CSS px。需要寬度是 logo 左緣到最後一個工具列按鈕右緣的距離。', '');
  out.push('標籤：', '');
  for (const [set, labels] of new Map(rows.map((r) => [r.set, r.labels]))) out.push(`- \`${set}\`：${labels.join('｜')}`);
  out.push('', '### 水平捲動', '', `| 頁面 | ${WIDTHS.map((w) => `${w}px`).join(' | ')} |`, `|---|${WIDTHS.map(() => '---').join('|')}|`);
  for (const p of overflow) out.push(`| \`${p.page}\` | ${WIDTHS.map((w) => (p.widths[w] ? '❌ 有' : '✅ 無')).join(' | ')} |`);
  out.push('', MARK_END);
  return out.join('\n');
}

function serve(root) {
  const server = createServer((req, res) => {
    const path = normalize(decodeURIComponent(new URL(req.url, 'http://x').pathname));
    let file = join(root, path);
    if (existsSync(`${file}.html`)) file = `${file}.html`;
    else if (existsSync(file) && statSync(file).isDirectory()) file = join(file, 'index.html');
    if (!file.startsWith(root) || !existsSync(file)) {
      res.writeHead(404).end();
      return;
    }
    res.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream' });
    createReadStream(file).pipe(res);
  });
  return new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve(server)));
}

function assertFonts() {
  const installed = execFileSync('fc-list', [':', 'family'], { encoding: 'utf8' });
  const missing = [...FONTS, CJK_FALLBACK].filter((f) => !installed.split('\n').some((line) => line.split(',').includes(f)));
  if (missing.length) throw new Error(`fonts not installed: ${missing.join(', ')}`);
}

async function measureRows(page, font) {
  await page.addStyleTag({ content: `[data-nav-fit] { font-family: "${font}", "${CJK_FALLBACK}", sans-serif !important; }` });
  await page.evaluate(() => document.fonts.ready);
  // The measurement rows sit inside <main>, which is narrower than the page header, so the available
  // width comes from the page's own header row; the rows only provide each label set's content width
  return page.$$eval('[data-nav-fit]', (headers) => {
    const real = document.querySelector('header.wf-header:not([data-nav-fit]) [data-fit-row]');
    const style = getComputedStyle(real);
    const available = Math.floor(real.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight));
    return headers.map((h) => {
      const row = h.querySelector('[data-fit-row]');
      const first = row.firstElementChild.getBoundingClientRect();
      const last = row.lastElementChild.getBoundingClientRect();
      return {
        set: h.dataset.navFit,
        labels: [...row.querySelectorAll('.primary li, .tools .locale, .tools .cta')].map((el) => el.textContent.replace('▾', '').trim()),
        content: Math.ceil(last.right - first.left),
        available,
      };
    });
  });
}

async function main() {
  if (!existsSync(join(DIST, 'wireframes', 'navigation.html'))) throw new Error('dist/wireframes/navigation.html not found; run npm run build first');
  assertFonts();
  const server = await serve(join(process.cwd(), DIST));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH, headless: true, args: ['--no-sandbox'] });
  const rows = [];
  const overflow = [];
  try {
    const page = await browser.newPage();
    for (const font of FONTS) {
      await page.setViewport({ width: DESKTOP, height: 800 });
      await page.goto(`${base}/wireframes/navigation`, { waitUntil: 'load' });
      for (const r of await measureRows(page, font)) rows.push({ ...r, font });
    }
    const pages = readdirSync(join(DIST, 'wireframes')).filter((f) => f.endsWith('.html')).map((f) => f.replace(/\.html$/, '')).sort();
    for (const name of ['index', ...pages.filter((p) => p !== 'index')]) {
      const widths = {};
      for (const width of WIDTHS) {
        await page.setViewport({ width, height: 800 });
        await page.goto(`${base}/wireframes${name === 'index' ? '' : `/${name}`}`, { waitUntil: 'load' });
        widths[width] = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
      }
      overflow.push({ page: name, widths });
    }
  } finally {
    await browser.close();
    server.close();
  }

  const doc = replaceSection(await readFile(DOC, 'utf8'), DOC, MARK_START, MARK_END, renderSection({ rows, overflow }));
  const check = process.argv.includes('--check');
  const stale = await emit([[DOC, doc]], { check, rerun: 'npm run build && node scripts/wireframe/nav-fit.mjs' });
  const scrolling = overflow.filter((p) => Object.values(p.widths).some(Boolean));
  for (const p of scrolling) console.error(`${p.page}: horizontal scrolling`);
  console.log(`${rows.length} rows measured, ${rows.filter((r) => !fits(r)).length} do not fit; ${overflow.length} pages, ${scrolling.length} scroll horizontally`);
  if (stale.length || scrolling.length) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
