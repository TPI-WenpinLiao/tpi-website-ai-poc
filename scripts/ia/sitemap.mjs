// New sitemap and template mapping for M2-01 (#8).
// Reads docs/research/inventory.csv, docs/ia/blog-categories.csv (scripts/ia/blog-categories.mjs)
// and the hand-written docs/ia/{nodes,templates,route-map,blog-slugs}.csv,
// maps every keep / rewrite / merge row to a sitemap node (and blog articles to their new slug), writes docs/ia/page-map.csv and
// docs/ia/sitemap-summary.json, and regenerates the marked section of docs/ia/sitemap.md.
// Re-run after editing any input or re-running scripts/inventory/audit.mjs: node scripts/ia/sitemap.mjs
// With --check it validates the same way but only compares the outputs to the files on disk (npm run check:ia).

import { readFile } from 'node:fs/promises';
import { readCsv, csvCell } from '../inventory/csv.mjs';
import { routeKey, ROUTE_ALIASES } from '../inventory/routes.mjs';
import { PATH_PATTERN, depth, emit, matchRoute, normalizeSlug, replaceSection } from './generated.mjs';

const INVENTORY = 'docs/research/inventory.csv';
const NODES = 'docs/ia/nodes.csv';
const TEMPLATES = 'docs/ia/templates.csv';
const ROUTE_MAP = 'docs/ia/route-map.csv';
const BLOG_CATEGORIES = 'docs/ia/blog-categories.csv';
const BLOG_SLUGS = 'docs/ia/blog-slugs.csv';
const PAGE_MAP = 'docs/ia/page-map.csv';
const SUMMARY = 'docs/ia/sitemap-summary.json';
const DOC = 'docs/ia/sitemap.md';
const MARK_START = '<!-- generated by scripts/ia/sitemap.mjs: start -->';
const MARK_END = '<!-- generated by scripts/ia/sitemap.mjs: end -->';

const LOCALES = ['zh-TW', 'en', 'vi'];
// Kinds without a template of their own: external links, downloadable files, and nav-only groupings
const UNTEMPLATED = new Set(['external', 'asset', 'group']);
const KINDS = new Set(['page', 'collection', ...UNTEMPLATED]);

const errors = [];

// Case-insensitive, locale-independent key; .vn legacy product routes resolve to their .com route
const keyOf = (url) => {
  const key = routeKey(url);
  return (ROUTE_ALIASES[key] ?? key).toLowerCase();
};

function validateNodes(nodes, templates) {
  const byId = new Map();
  for (const n of nodes) {
    if (byId.has(n.id)) errors.push(`duplicate node id: ${n.id}`);
    byId.set(n.id, n);
  }
  for (const n of nodes) {
    if (n.parent && !byId.has(n.parent)) errors.push(`node ${n.id}: parent "${n.parent}" not found`);
    if (!n.parent && n.id !== 'home') errors.push(`node ${n.id}: only home may have no parent`);
    if (!KINDS.has(n.kind)) errors.push(`node ${n.id}: invalid kind "${n.kind}"`);
    if (n.path && !PATH_PATTERN.test(n.path)) errors.push(`node ${n.id}: path "${n.path}" breaks the URL rule (ADR 0002)`);
    if (UNTEMPLATED.has(n.kind) ? n.template : !templates.has(n.template)) {
      errors.push(`node ${n.id}: template "${n.template}" not allowed for kind ${n.kind}`);
    }
    // Walk to the root to catch cycles
    const seen = new Set();
    for (let cur = n; cur?.parent; cur = byId.get(cur.parent)) {
      if (seen.has(cur.id)) { errors.push(`node ${n.id}: parent cycle`); break; }
      seen.add(cur.id);
    }
  }
  return byId;
}

function mapRow(row, ctx) {
  const { routes, byId, used, subCategory } = ctx;
  // Blog articles (including the three mis-typed as categories) join the article collection.
  // The new category comes from the old subcategory (blog API), else the main category in the URL.
  const isArticle = row.page_type === 'blog-post' || (row.page_type === 'blog-category' && row.disposition === 'keep');
  if (isArticle) {
    const sub = subCategory.get(row.url);
    if (row.page_type === 'blog-post' && sub === undefined) errors.push(`blog article missing from ${BLOG_CATEGORIES}: ${row.url}`);
    const categoryKey = sub ? keyOf(new URL(sub, row.url).href) : keyOf(row.final_url).split('/').slice(0, 3).join('/');
    const category = routes.get(categoryKey);
    if (!category || byId.get(category)?.parent !== 'blog') {
      errors.push(`blog article without a new category (${categoryKey}): ${row.url}`);
      return {};
    }
    used.add(categoryKey);
    return { node: 'blog-post', blog_category: category };
  }
  if (row.page_type === 'news') return { node: 'news-article' };

  const route = matchRoute(routes, keyOf(row.final_url));
  if (!route) {
    errors.push(`no route-map entry for ${keyOf(row.final_url)}: ${row.url}`);
    return {};
  }
  used.add(route);
  return { node: routes.get(route) };
}

// Blog article slug under /blog (ADR 0002): the old slug lowercased, runs of "-" collapsed, edge "-" trimmed.
// A slug equal to a category slug or "page" takes the old category segment as prefix.
// Merge rows take the slug of their target, the first URL in disposition_reason (scripts/inventory/audit.mjs).
// docs/ia/blog-slugs.csv gives a translated article the slug of its other locale versions (ADR 0002:
// slugs are shared across locales, and hreflang pairs pages by path).
function assignBlogSlugs(mapped, nodes, slugOverrides) {
  const reserved = new Set(['page', ...nodes.filter((n) => n.parent === 'blog' && n.kind === 'page').map((n) => n.path.split('/').pop())]);
  const articles = mapped.filter((r) => r.node === 'blog-post');
  const kept = new Map();
  const seen = new Map();
  for (const r of articles.filter((a) => a.disposition !== 'merge')) {
    const segments = new URL(r.url).pathname.split('/').filter(Boolean);
    let slug = normalizeSlug(segments.at(-1));
    if (reserved.has(slug)) slug = normalizeSlug(`${segments.at(-2)}-${slug}`);
    const override = slugOverrides.get(r.url);
    if (override) {
      slugOverrides.delete(r.url);
      slug = override.blog_slug;
    }
    if (reserved.has(slug) || !PATH_PATTERN.test(`/${slug}`)) errors.push(`blog slug "${slug}" breaks the URL rule (ADR 0002): ${r.url}`);
    const key = `${r.locale} ${slug}`;
    if (seen.has(key)) errors.push(`duplicate blog slug ${key}: ${seen.get(key)} and ${r.url}`);
    seen.set(key, r.url);
    kept.set(r.url, r);
    r.blog_slug = slug;
  }
  for (const r of articles.filter((a) => a.disposition === 'merge')) {
    const target = kept.get(r.disposition_reason.match(/https:\/\/\S+?(?=[\s，。]|$)/)?.[0]);
    if (!target || target.locale !== r.locale) errors.push(`blog merge row without a kept target in the same locale: ${r.url}`);
    else r.blog_slug = target.blog_slug;
  }
  for (const url of slugOverrides.keys()) errors.push(`${BLOG_SLUGS}: not a kept blog article: ${url}`);
}

function mermaid(nodes) {
  const label = (n) => {
    const tag = n.template || n.kind;
    return `"${n.title}<br/>${tag}"`;
  };
  const shape = (n) => ({
    collection: `[[${label(n)}]]`,
    external: `>${label(n)}]`,
    asset: `[(${label(n)})]`,
    group: `{{${label(n)}}}`,
  })[n.kind] ?? `[${label(n)}]`;
  const id = (n) => n.id.replace(/-/g, '_');
  const lines = ['```mermaid', 'flowchart LR'];
  for (const n of nodes) lines.push(`  ${id(n)}${shape(n)}`);
  const byId = new Map(nodes.map((n) => [n.id, n]));
  for (const n of nodes) if (n.parent) lines.push(`  ${id(byId.get(n.parent))} --> ${id(n)}`);
  lines.push('```');
  return lines.join('\n');
}

function generatedSection(nodes, templates, byId, counts) {
  const count = (id, locale) => counts.get(id)?.[locale] ?? 0;
  const total = (id) => LOCALES.reduce((s, l) => s + count(id, l), 0);
  const out = [MARK_START, '', '### 頁面階層', '', '圖例：方框為單一頁面，雙框為集合（一個模板產生多頁），旗形為外部連結，圓柱為下載檔案，六角形為只用於分組的節點。框內第二行為模板。', '', mermaid(nodes), ''];

  out.push('### 模板清單', '', '| 模板 | 用途 | 節點數 | 對應 inventory 列數 |', '|---|---|--:|--:|');
  for (const [tid, t] of templates) {
    const ids = nodes.filter((n) => n.template === tid).map((n) => n.id);
    out.push(`| \`${tid}\` | ${t.purpose} | ${ids.length} | ${ids.reduce((s, id) => s + total(id), 0)} |`);
  }

  out.push('', '### 節點與模板對應', '', '路徑依 [ADR 0002](../decisions/0002-url-and-locale.md)：有現站頁面的沿用現站路徑（去掉語系前綴、轉小寫），新頁依階層命名；en、vi 加 `/en`、`/vi` 前綴。列數為對應到該節點的 inventory 列數（keep／rewrite／merge）。', '');
  out.push('| 節點 | 模板 | 路徑 | zh-TW | en | vi | 備註 |', '|---|---|---|--:|--:|--:|---|');
  for (const n of nodes) {
    const indent = '　'.repeat(depth(n, byId));
    const path = n.path ? `\`${n.path}\`` : '';
    out.push(`| ${indent}${n.title}（\`${n.id}\`） | ${n.template ? `\`${n.template}\`` : n.kind} | ${path} | ${count(n.id, 'zh-TW')} | ${count(n.id, 'en')} | ${count(n.id, 'vi')} | ${n.note} |`);
  }
  out.push('', MARK_END);
  return out.join('\n');
}

async function main() {
  const rows = await readCsv(INVENTORY);
  const nodes = await readCsv(NODES);
  const templates = new Map((await readCsv(TEMPLATES)).map((t) => [t.id, t]));
  const routeRows = await readCsv(ROUTE_MAP);
  const subCategory = new Map((await readCsv(BLOG_CATEGORIES)).map((b) => [b.url, b.sub_category]));

  const byId = validateNodes(nodes, templates);
  const routes = new Map();
  for (const r of routeRows) {
    if (routes.has(r.route)) errors.push(`duplicate route: ${r.route}`);
    if (r.route !== r.route.toLowerCase()) errors.push(`route must be lowercase: ${r.route}`);
    const target = byId.get(r.node);
    if (!target) errors.push(`route ${r.route}: node "${r.node}" not found`);
    else if (target.kind === 'group') errors.push(`route ${r.route}: cannot map to group node ${r.node}`);
    routes.set(r.route, r.node);
  }

  const used = new Set();
  const mapped = rows
    .filter((r) => r.disposition !== 'drop')
    .map((r) => {
      const { node, blog_category = '' } = mapRow(r, { routes, byId, used, subCategory });
      return { url: r.url, locale: r.locale, page_type: r.page_type, disposition: r.disposition, disposition_reason: r.disposition_reason, node, template: byId.get(node)?.template ?? '', blog_category };
    });
  const slugOverrides = await readCsv(BLOG_SLUGS);
  for (const o of slugOverrides) if (!o.reason) errors.push(`${BLOG_SLUGS}: reason is empty: ${o.url}`);
  assignBlogSlugs(mapped, nodes, new Map(slugOverrides.map((o) => [o.url, o])));
  for (const route of routes.keys()) if (!used.has(route)) errors.push(`route-map entry not used by any inventory row: ${route}`);

  // Every node needs inventory rows or a note saying why it has none (new page, no detail pages yet)
  const counts = new Map();
  for (const r of mapped) {
    if (!r.node) continue;
    const c = counts.get(r.node) ?? {};
    c[r.locale] = (c[r.locale] ?? 0) + 1;
    counts.set(r.node, c);
  }
  for (const n of nodes) {
    if (!UNTEMPLATED.has(n.kind) && !counts.has(n.id) && !n.note) errors.push(`node ${n.id} has no inventory rows; add a note`);
  }

  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }

  const columns = ['url', 'locale', 'page_type', 'disposition', 'node', 'template', 'blog_category', 'blog_slug'];
  const csv = [columns.join(','), ...mapped.map((r) => columns.map((c) => csvCell(r[c])).join(','))].join('\n');

  const byTemplate = {};
  for (const r of mapped) byTemplate[r.template] = (byTemplate[r.template] ?? 0) + 1;
  const summary = {
    mappedRows: mapped.length,
    byDisposition: Object.fromEntries(['keep', 'rewrite', 'merge'].map((d) => [d, mapped.filter((r) => r.disposition === d).length])),
    nodes: nodes.length,
    templates: templates.size,
    byTemplate: Object.fromEntries(Object.entries(byTemplate).sort()),
    byNode: Object.fromEntries(nodes.filter((n) => counts.has(n.id)).map((n) => [n.id, counts.get(n.id)])),
    nodesWithoutRows: nodes.filter((n) => !counts.has(n.id)).map((n) => n.id),
  };
  const doc = replaceSection(await readFile(DOC, 'utf8'), DOC, MARK_START, MARK_END, generatedSection(nodes, templates, byId, counts));

  const check = process.argv.includes('--check');
  const stale = await emit([
    [PAGE_MAP, `﻿${csv}\n`],
    [SUMMARY, `${JSON.stringify(summary, null, 2)}\n`],
    [DOC, doc],
  ], { check, rerun: 'node scripts/ia/sitemap.mjs' });
  if (stale.length) process.exit(1);

  console.log(`${mapped.length} rows mapped to ${counts.size} of ${nodes.length} nodes${check ? ', outputs up to date' : ''}:`, summary.byDisposition);
}

await main();
