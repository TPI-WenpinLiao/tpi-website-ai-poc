// Site navigation for M2-02 (#9).
// Reads the hand-written docs/ia/navigation.csv and docs/ia/nodes.csv, checks the navigation against
// the sitemap, and regenerates the marked section of docs/ia/navigation.md.
// Re-run after editing either CSV: node scripts/ia/navigation.mjs
// With --check it validates the same way but only compares the output to the file on disk (npm run check:ia).

import { readFile } from 'node:fs/promises';
import { readCsv } from '../inventory/csv.mjs';
import { depth, emit, replaceSection } from './generated.mjs';

const NODES = 'docs/ia/nodes.csv';
const NAV = 'docs/ia/navigation.csv';
const DOC = 'docs/ia/navigation.md';
const MARK_START = '<!-- generated by scripts/ia/navigation.mjs: start -->';
const MARK_END = '<!-- generated by scripts/ia/navigation.mjs: end -->';

// footer-bottom is the flat row under the footer columns, next to the copyright notice
const AREAS = ['utility', 'header', 'footer', 'footer-bottom', 'none'];
const AREA_LABEL = { utility: '工具列', header: 'header', footer: 'footer', 'footer-bottom': 'footer 最底列', none: '不進導覽' };
// Subtrees whose pages never need a nav entry; every other page and external link at any depth does
const OPTIONAL_ROOTS = new Set(['utilities']);
// Groups whose pages never appear in the header menus (search sits in the utility bar instead)
const NOT_IN_HEADER = new Set(['legal', 'utilities']);
// Only these kinds have a single URL to link to
const LINKABLE = new Set(['page', 'external']);

const errors = [];

function ancestors(n, byId) {
  const out = [];
  for (let cur = byId.get(n.parent); cur; cur = byId.get(cur.parent)) out.push(cur.id);
  return out;
}

// Rows of one area become a forest; a row's key is its node id, or its label when it has no node
function buildTree(rows, byId, area) {
  const items = new Map();
  const parentOf = new Map();
  const roots = [];
  for (const r of rows) {
    const node = r.node ? byId.get(r.node) : null;
    if (r.node && !node) { errors.push(`${area}: node "${r.node}" not found`); continue; }
    if (!r.node && !r.label) { errors.push(`${area}: row needs a node or a label`); continue; }
    if (area !== 'none' && node && !LINKABLE.has(node.kind)) errors.push(`${area}: ${r.node} is a ${node.kind} node with no single page to link to`);
    // Labels go into Mermaid strings and Markdown table cells unescaped
    if (/["|]/.test(r.label)) errors.push(`${area}: label "${r.label}" must not contain " or |`);
    const key = r.node || r.label;
    if (items.has(key)) errors.push(`${area}: duplicate item "${key}"`);
    const item = { key, node, label: r.label || node.title, note: r.note, children: [] };
    items.set(key, item);
    if (!r.parent) roots.push(item);
    else if (items.has(r.parent)) { items.get(r.parent).children.push(item); parentOf.set(key, items.get(r.parent)); }
    else errors.push(`${area}: parent "${r.parent}" of "${key}" must appear on an earlier row`);
  }
  return { items, parentOf, roots };
}

function mermaid(roots) {
  const lines = ['```mermaid', 'flowchart LR', '  root(("header"))'];
  let i = 0;
  const walk = (item, parentId) => {
    const id = `n${i++}`;
    const shape = item.node ? `["${item.label}"]` : `{{"${item.label}"}}`;
    lines.push(`  ${id}${shape}`, `  ${parentId} --> ${id}`);
    for (const c of item.children) walk(c, id);
  };
  for (const r of roots) walk(r, 'root');
  lines.push('```');
  return lines.join('\n');
}

function footerTable(roots) {
  const cols = roots.map((r) => [r.label, ...r.children.map((c) => c.label)]);
  const height = Math.max(...cols.map((c) => c.length));
  const out = [`| ${cols.map((c) => c[0]).join(' | ')} |`, `|${cols.map(() => '---').join('|')}|`];
  for (let row = 1; row < height; row++) out.push(`| ${cols.map((c) => c[row] ?? '').join(' | ')} |`);
  return out.join('\n');
}

function pathOf(item, tree) {
  const labels = [item.label];
  for (let cur = tree.parentOf.get(item.key); cur; cur = tree.parentOf.get(cur.key)) labels.unshift(cur.label);
  return labels.join(' > ');
}

function generatedSection(trees, listed, byId) {
  const out = [MARK_START, ''];
  out.push('### header', '', '方框為連到頁面的項目，六角形為只用來展開選單、沒有連結的項目。', '', mermaid(trees.header.roots), '');
  out.push('### footer', '', footerTable(trees.footer.roots), '');
  out.push('最底列：', '', ['版權聲明', ...trees['footer-bottom'].roots.map((r) => r.label)].join('｜'), '');

  out.push('### 節點在導覽中的位置', '', 'sitemap 中所有頁面與外部連結（不含功能頁群組）都要出現在 header、footer 或工具列，或列為「不進導覽」並寫理由。script 依此檢查。', '');
  out.push('| 節點 | 位置 |', '|---|---|');
  for (const n of listed) {
    const indent = '　'.repeat(depth(n, byId));
    const cell = AREAS
      .flatMap((a) => (trees[a].items.has(n.id) ? [a === 'none' ? `不進導覽：${trees[a].items.get(n.id).note}` : `${AREA_LABEL[a]}：${pathOf(trees[a].items.get(n.id), trees[a])}`] : []))
      .join('<br/>');
    out.push(`| ${indent}${n.title}（\`${n.id}\`） | ${cell} |`);
  }

  const t = trees;
  out.push('', '### 統計', '', '| header 第一層 | header 項目 | footer 欄 | footer 項目 | footer 最底列 | 不進導覽 |', '|--:|--:|--:|--:|--:|--:|');
  out.push(`| ${t.header.roots.length} | ${t.header.items.size} | ${t.footer.roots.length} | ${t.footer.items.size - t.footer.roots.length} | ${t['footer-bottom'].items.size} | ${t.none.items.size} |`);
  out.push('', MARK_END);
  return out.join('\n');
}

async function main() {
  const nodes = await readCsv(NODES);
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const rows = await readCsv(NAV);
  for (const r of rows) if (!AREAS.includes(r.area)) errors.push(`invalid area "${r.area}"`);

  const required = nodes.filter((n) => ['page', 'external'].includes(n.kind)
    && !ancestors(n, byId).some((a) => OPTIONAL_ROOTS.has(a)));

  const trees = Object.fromEntries(AREAS.map((a) => [a, buildTree(rows.filter((r) => r.area === a), byId, a)]));
  for (const item of trees.none.items.values()) {
    if (!item.node) errors.push(`none: "${item.key}" must be a node`);
    if (!item.note) errors.push(`none: ${item.key} needs a note saying why`);
    for (const a of ['utility', 'header', 'footer', 'footer-bottom']) if (trees[a].items.has(item.key)) errors.push(`${item.key} is in both none and ${a}`);
  }
  for (const item of trees.header.items.values()) {
    if (item.node && [item.key, ...ancestors(item.node, byId)].some((x) => NOT_IN_HEADER.has(x))) errors.push(`header: ${item.key} may not be in the header`);
  }
  // The footer is one level of unlinked column headings with links under them; footerTable renders only that
  if (!trees.footer.roots.length) errors.push('footer: no columns');
  for (const col of trees.footer.roots) {
    if (col.node) errors.push(`footer: column heading "${col.key}" must be a label, not a node`);
    for (const c of col.children) if (c.children.length) errors.push(`footer: ${c.key} may not have children`);
  }
  // The bottom row is one flat row of links
  for (const r of rows) if (r.area === 'footer-bottom' && r.parent) errors.push(`footer-bottom: ${r.node || r.label} may not have a parent`);
  for (const item of trees['footer-bottom'].roots) if (!item.node) errors.push(`footer-bottom: "${item.key}" must be a node`);
  for (const n of required) {
    if (!AREAS.some((a) => trees[a].items.has(n.id))) errors.push(`node ${n.id} is not in any nav area; add it or list it under area none with a note`);
  }

  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }

  const listed = nodes.filter((n) => required.includes(n) || AREAS.some((a) => trees[a].items.has(n.id)));
  const doc = replaceSection(await readFile(DOC, 'utf8'), DOC, MARK_START, MARK_END, generatedSection(trees, listed, byId));

  const check = process.argv.includes('--check');
  const stale = await emit([[DOC, doc]], { check, rerun: 'node scripts/ia/navigation.mjs' });
  if (stale.length) process.exit(1);

  console.log(`header ${trees.header.items.size} items, footer ${trees.footer.items.size}, footer-bottom ${trees['footer-bottom'].items.size}, none ${trees.none.items.size}${check ? ', output up to date' : ''}`);
}

await main();
