// Tests for scripts/ia/redirects.mjs. Run: npm run test:scripts

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildRedirects, toRedirects } from './redirects.mjs';

const nodes = [
  { id: 'home', kind: 'page', path: '/' },
  { id: 'gadodido', kind: 'page', path: '/products/gadodido' },
  { id: 'blog-ai', kind: 'page', path: '/blog/ai' },
  { id: 'blog-post', kind: 'collection', path: '/blog/{slug}' },
  { id: 'media-center', kind: 'page', path: '/media-center' },
  { id: 'news-article', kind: 'collection', path: '/media-center/{id}' },
  { id: 'subscribe', kind: 'page', path: '/subscribe' },
];
const row = (url, locale, disposition) => ({ url, locale, disposition });
const mapped = (url, locale, node, blog_slug = '') => ({ url, locale, node, blog_slug });

const inventory = [
  row('https://www.tpisoftware.com/', 'zh-TW', 'rewrite'),
  row('https://www.tpisoftware.com/en', 'en', 'rewrite'),
  row('https://www.tpisoftware.com/products/gadoDIDO', 'zh-TW', 'merge'),
  row('https://www.tpisoftware.com/blog/dx', 'zh-TW', 'merge'),
  row('https://www.tpisoftware.com/blog/ai/Chatbot-NLU', 'zh-TW', 'keep'),
  row('https://www.tpisoftware.com/media-center', 'zh-TW', 'rewrite'),
  row('https://www.tpisoftware.com/media-center/12', 'zh-TW', 'keep'),
  row('https://www.tpisoftware.com/media-center/13', 'zh-TW', 'drop'),
  row('https://www.tpisoftware.com/subscribe', 'zh-TW', 'rewrite'),
  row('https://www.tpisoftware.com/epaper/2019/01', 'zh-TW', 'drop'),
  row('https://www.tpisoftware.com/ja/partners', 'ja', 'drop'),
  row('https://www.tpisoftware.vn/products/gadodido', 'vi', 'keep'),
];
const pageMap = [
  mapped('https://www.tpisoftware.com/', 'zh-TW', 'home'),
  mapped('https://www.tpisoftware.com/en', 'en', 'home'),
  mapped('https://www.tpisoftware.com/products/gadoDIDO', 'zh-TW', 'gadodido'),
  mapped('https://www.tpisoftware.com/blog/dx', 'zh-TW', 'blog-ai'),
  mapped('https://www.tpisoftware.com/blog/ai/Chatbot-NLU', 'zh-TW', 'blog-post', 'chatbot-nlu'),
  mapped('https://www.tpisoftware.com/media-center', 'zh-TW', 'media-center'),
  mapped('https://www.tpisoftware.com/media-center/12', 'zh-TW', 'news-article'),
  mapped('https://www.tpisoftware.com/subscribe', 'zh-TW', 'subscribe'),
  mapped('https://www.tpisoftware.vn/products/gadodido', 'vi', 'gadodido'),
];
const dropTargets = [{ route: '/epaper/*', node: 'subscribe' }];

test('buildRedirects maps every inventory URL by the ADR 0002 rules', () => {
  const { rows, errors } = buildRedirects({ inventory, pageMap, nodes, dropTargets });
  assert.deepEqual(errors, []);
  const byFrom = Object.fromEntries(rows.map((r) => [r.from, `${r.to} ${r.status}`]));
  assert.deepEqual(byFrom, {
    'https://www.tpisoftware.com/': '/ 200',
    'https://www.tpisoftware.com/en': '/en 200',
    'https://www.tpisoftware.com/products/gadoDIDO': '/products/gadodido 301',
    'https://www.tpisoftware.com/blog/dx': '/blog/ai 301',
    'https://www.tpisoftware.com/blog/ai/Chatbot-NLU': '/blog/chatbot-nlu 301',
    'https://www.tpisoftware.com/media-center': '/media-center 200',
    'https://www.tpisoftware.com/media-center/12': '/media-center/12 200',
    'https://www.tpisoftware.com/media-center/13': '/media-center 301',
    'https://www.tpisoftware.com/subscribe': '/subscribe 200',
    'https://www.tpisoftware.com/epaper/2019/01': '/subscribe 301',
    'https://www.tpisoftware.com/ja/partners': '/en 301',
    'https://www.tpisoftware.vn/products/gadodido': '/vi/products/gadodido 301',
    'https://www.tpisoftware.com/ja/*': '/en 301',
    'https://www.tpisoftware.com/vn/*': '/vi/:splat 301',
    'https://www.tpisoftware.vn/*': '/vi/:splat 301',
  });
});

test('buildRedirects rejects a dropped page without a parent or with an unknown drop target', () => {
  const { errors } = buildRedirects({
    inventory: [...inventory, row('https://www.tpisoftware.com/2023tpiday', 'zh-TW', 'drop')],
    pageMap,
    nodes,
    dropTargets: [{ route: '/2023tpiday', node: 'evnets' }],
  });
  assert.deepEqual(errors, [
    'dropped row without a parent page in zh-TW; add it to docs/ia/drop-targets.csv: https://www.tpisoftware.com/epaper/2019/01',
    'docs/ia/drop-targets.csv: node "evnets" not found: https://www.tpisoftware.com/2023tpiday',
  ]);
});

test('toRedirects writes main-host redirects, static before splats, and skips unchanged rows', () => {
  const { rows } = buildRedirects({ inventory, pageMap, nodes, dropTargets });
  const out = toRedirects(rows);
  assert.deepEqual(out.errors, []);
  assert.equal(out.text, [
    '# generated by scripts/ia/redirects.mjs from docs/ia/redirects.csv',
    '/products/gadoDIDO /products/gadodido 301',
    '/blog/dx /blog/ai 301',
    '/blog/ai/Chatbot-NLU /blog/chatbot-nlu 301',
    '/media-center/13 /media-center 301',
    '/epaper/2019/01 /subscribe 301',
    '/ja/partners /en 301',
    '/ja/* /en 301',
    '/vn/* /vi/:splat 301',
    '',
  ].join('\n'));
  assert.deepEqual([out.static, out.dynamic], [6, 2]);
});

test('toRedirects rejects rules that match a new page', () => {
  const rows = [
    { from: 'https://www.tpisoftware.com/products/gadodido', to: '/', status: '301' },
    { from: 'https://www.tpisoftware.com/products/gadoDIDO', to: '/products/gadodido', status: '301' },
    { from: 'https://www.tpisoftware.com/blog/*', to: '/blog/ai', status: '301' },
  ];
  assert.deepEqual(toRedirects(rows).errors, [
    'redirect matches the new page /products/gadodido (loop or shadowed page): /products/gadodido / 301',
    'redirect matches the new page /blog/ai (loop or shadowed page): /blog/* /blog/ai 301',
  ]);
  // Pages no redirect points to come from nodes.csv, in every locale
  const unlinked = [{ from: 'https://www.tpisoftware.com/en/subscribe', to: '/en', status: '301' }];
  assert.deepEqual(toRedirects(unlinked, nodes).errors, [
    'redirect matches the new page /en/subscribe (loop or shadowed page): /en/subscribe /en 301',
  ]);
});

test('toRedirects enforces the Cloudflare Pages limits', () => {
  const many = Array.from({ length: 2001 }, (_, i) => ({ from: `https://www.tpisoftware.com/old/${i}`, to: '/', status: '301' }));
  const long = { from: `https://www.tpisoftware.com/${'a'.repeat(1000)}`, to: '/', status: '301' };
  const { errors } = toRedirects([...many, long]);
  assert.equal(errors.length, 2);
  assert.match(errors[0], /^2002 static redirects, Cloudflare Pages allows 2000$/);
  assert.match(errors[1], /^redirect longer than 1000 characters: \/a+ \/ 301$/);
});
