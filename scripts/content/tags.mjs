// Builds src/content/tags.yaml, the controlled tag list for blog.tags. Tag ids and the current-site
// subcategory each tag replaces come from the "tag 清單" table in docs/ia/content-model.md; display
// names are the current site's subcategory names from the blog category API, per locale.
// Run: node scripts/content/tags.mjs (needs the current site; not part of npm run check)

import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { stringify } from 'yaml';

const MODEL = 'docs/ia/content-model.md';
const OUT = 'src/content/tags.yaml';
const LOCALES = ['zh-TW', 'en', 'vi'];
// Same API languages as scripts/ia/blog-categories.mjs
const API_LANG = { 'zh-TW': 'ZH-TW', en: 'EN-US', vi: 'VI-VN' };

// Rows of the "### tag 清單" table: | `tag` | `zh/path`（n） | … | → { id, paths: { locale: '/blog/zh/path' } }
export function parseTagTable(markdown) {
  const section = markdown.split(/^### tag 清單$/m)[1]?.split(/^#{2,3} /m)[0];
  if (!section) throw new Error(`${MODEL}: "### tag 清單" section not found`);
  // Only the first table of the section; the JSON-LD table follows without a heading
  const lines = section.split('\n');
  const start = lines.findIndex((l) => l.startsWith('|'));
  const end = lines.findIndex((l, i) => i > start && !l.startsWith('|'));
  const tags = [];
  for (const line of lines.slice(start, end < 0 ? undefined : end)) {
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    const id = cells[0]?.match(/^`([a-z0-9-]+)`$/)?.[1];
    if (!id) continue;
    if (cells.length !== LOCALES.length + 1) throw new Error(`${MODEL}: tag ${id} has ${cells.length} cells`);
    const paths = {};
    LOCALES.forEach((locale, i) => {
      const path = cells[i + 1].match(/^`([^`]+)`/)?.[1];
      if (path) paths[locale] = `/blog/${path}`;
    });
    tags.push({ id, paths });
  }
  if (!tags.length) throw new Error(`${MODEL}: tag table is empty`);
  return tags;
}

// Category API response → Map(custUrl → categoryName), main categories and subcategories alike.
// en custUrls carry the locale prefix (/en/blog/…); the tag table does not.
export function categoryNames(content) {
  const names = new Map();
  const add = (c) => names.set(c.custUrl.replace(/^\/(?:en|vi)(?=\/)/, ''), c.categoryName);
  for (const c of content) {
    add(c);
    for (const s of c.subcategories ?? []) add(s);
  }
  return names;
}

export function buildTags(tags, namesByLocale) {
  return tags.map(({ id, paths }) => {
    const name = {};
    for (const [locale, path] of Object.entries(paths)) {
      const n = namesByLocale[locale].get(path);
      if (!n) throw new Error(`tag ${id}: ${locale} category ${path} not found on the current site`);
      name[locale] = n.trim();
    }
    return { id, name };
  });
}

async function main() {
  // Imported here: http.mjs re-executes the process with proxy support on import
  const { request } = await import('../inventory/http.mjs');
  const tags = parseTagTable(await readFile(MODEL, 'utf8'));
  const namesByLocale = {};
  for (const locale of LOCALES) {
    const res = await request('https://www.tpisoftware.com/cms/api/v1/f/article/category', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'X-Lang': API_LANG[locale] },
      body: '{}',
    });
    if (!res.ok) throw new Error(`category API ${locale}: HTTP ${res.status}`);
    namesByLocale[locale] = categoryNames((await res.json()).data.content);
  }
  const header = `# Generated by scripts/content/tags.mjs from ${MODEL} and the current site's blog categories. Do not edit.\n`;
  await writeFile(OUT, header + stringify(buildTags(tags, namesByLocale)));
  console.log(`${tags.length} tags written to ${OUT}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
