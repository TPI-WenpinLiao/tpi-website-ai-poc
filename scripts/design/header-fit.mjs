// Header width check (M4-04, #23; measures the real pages since #240): does each locale's
// SiteHeader hold its first-level menu, language menu and contact button in one row from the
// narrowest desktop width (--bp-lg-up, 1024px) up?
// Serves dist/ and, for every locale, opens the home page (the `wide` header, on the home grid) and
// one inner page (the content-width header). On each it compares the bar's natural width, laid out
// with max-content, with the width it has, and counts the lines of every first-level label and of
// the contact button. The two must agree: a label that wraps while the widths say it fits means the
// measurement no longer matches the header, which is how docs/design/nav-fit.md once showed 33px to
// spare for vi while the real menu wrapped (#240: the old fixture labels had a shorter button).
// Widths: the narrowest of each spacing regime of SiteHeader (--bp-lg-up and --bp-lg-wide-up); the
// bar only gets wider from there, and its content is the same at every width of a regime.
// Run after npm run build:
//   node scripts/design/header-fit.mjs          measure and rewrite the marked section of nav-fit.md
//   node scripts/design/header-fit.mjs --check  fail when a header doesn't fit or wraps; nav-fit.md
//                                               is not compared (part of npm run check)
// --check leaves the document alone: zh-TW's widths depend on the system's CJK fallback font, which
// differs between GitHub's Playwright image and the cloud session. Both modes exit 1 on a problem.
// Uses CHROME_PATH (set by the SessionStart hook), else CHROME_BIN (set on GitHub's runners), else
// the installed Chrome.

import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import puppeteer from 'puppeteer-core';
import { emit, replaceSection } from '../ia/generated.mjs';
import { serve } from '../lib/static-server.mjs';
import { LAUNCH_ARGS } from './scene-wait.mjs';

const DIST = 'dist';
const DOC = 'docs/design/nav-fit.md';
const MARK_START = '<!-- generated by scripts/design/header-fit.mjs: start -->';
const MARK_END = '<!-- generated by scripts/design/header-fit.mjs: end -->';
// --bp-lg-up (64rem) and --bp-lg-wide-up (80rem) in src/styles/media.css
export const WIDTHS = [1024, 1280];
// Every locale's home page and the same inner page (about-us exists in all three)
export const PAGES = [
  { locale: 'zh-TW', header: '首頁', path: '/' },
  { locale: 'zh-TW', header: '內頁', path: '/about-us' },
  { locale: 'en', header: '首頁', path: '/en' },
  { locale: 'en', header: '內頁', path: '/en/about-us' },
  { locale: 'vi', header: '首頁', path: '/vi' },
  { locale: 'vi', header: '內頁', path: '/vi/about-us' },
];

export const fits = ({ content, available }) => content <= available;

// What is wrong with one measured row: it doesn't fit, a label wraps, the two disagree, or a label
// wasn't measured at all (missing from the header, or no visible text found: a check that silently
// skips a label is how #240 went unnoticed)
export function problems(row) {
  const out = [];
  const where = `${row.path} at ${row.width}px`;
  const wrapped = row.labels.filter((l) => l.lines > 1).map((l) => l.text);
  const unmeasured = row.labels.filter((l) => l.lines === 0).map((l) => l.text || '(no text)');
  if (row.missing.length) out.push(`${where}: not found in the header: ${row.missing.join(', ')}`);
  if (unmeasured.length) out.push(`${where}: no visible text measured: ${unmeasured.join(', ')}`);
  if (!fits(row)) out.push(`${where}: the header needs ${row.content}px, has ${row.available}px`);
  if (wrapped.length) out.push(`${where}: wraps: ${wrapped.join(', ')}`);
  if (fits(row) && wrapped.length) out.push(`${where}: the widths say it fits but labels wrap; the measurement no longer matches the header`);
  return out;
}

export function renderSection(rows) {
  const out = [MARK_START, '', '| 語系 | header | 視窗寬度 | 需要寬度 | 可用寬度 | 餘裕 | 一行 |', '|---|---|--:|--:|--:|--:|---|'];
  for (const r of rows) {
    const ok = problems(r).length === 0;
    out.push(`| ${r.locale} | ${r.header}（\`${r.path}\`） | ${r.width} | ${r.content} | ${r.available} | ${r.available - r.content} | ${ok ? '✅' : '❌'} |`);
  }
  out.push('', '寬度單位為 CSS px。需要寬度是 header 列不換行、不壓縮時的內容寬度（logo 到聯絡按鈕）；可用寬度是列扣掉左右留白。zh-TW 的寬度取決於系統的中文字型，換一台機器量會不同。', '');
  out.push('標籤：', '');
  const seen = new Set();
  for (const r of rows) {
    if (seen.has(r.locale)) continue;
    seen.add(r.locale);
    out.push(`- ${r.locale}：${r.labels.map((l) => l.text).join('｜')}`);
  }
  out.push('', MARK_END);
  return out.join('\n');
}

// Runs in the page: the header bar's widths and the line count of each label
function measure() {
  const bar = document.querySelector('header.site-header .bar');
  const nav = [...bar.querySelectorAll('.desktop-nav .top > li > details > summary')];
  const locale = bar.querySelector('.tools .locale summary');
  const cta = bar.querySelector('.tools .cta a');
  const missing = [
    ...(nav.length ? [] : ['first-level menu']),
    ...(locale ? [] : ['language menu']),
    ...(cta ? [] : ['contact button']),
  ];
  // The visible text at any depth: not the caret, the icon or the sr-only prefix
  const visibleText = (el) => {
    const nodes = [];
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let n = walker.nextNode(); n; n = walker.nextNode()) {
      if (n.textContent.trim() && !n.parentElement.closest('.sr-only')) nodes.push(n);
    }
    return nodes;
  };
  const labels = [...nav, locale, cta].filter(Boolean).map((el) => {
    const nodes = visibleText(el);
    const tops = new Set();
    for (const n of nodes) {
      const range = document.createRange();
      range.selectNodeContents(n);
      for (const rect of range.getClientRects()) if (rect.width > 0) tops.add(Math.round(rect.top));
    }
    return { text: nodes.map((n) => n.textContent.trim()).join(' '), lines: tops.size };
  });
  const style = getComputedStyle(bar);
  const padding = parseFloat(style.paddingLeft) + parseFloat(style.paddingRight);
  const available = Math.floor(bar.clientWidth - padding);
  bar.style.inlineSize = 'max-content';
  bar.style.maxInlineSize = 'none';
  const content = Math.ceil(bar.getBoundingClientRect().width - padding);
  return { labels, missing, content, available };
}

async function main() {
  const check = process.argv.includes('--check');
  if (!existsSync(join(DIST, 'index.html'))) throw new Error('dist/index.html not found; run npm run build first');
  const server = await serve(join(process.cwd(), DIST));
  const base = `http://127.0.0.1:${server.address().port}`;
  const executablePath = process.env.CHROME_PATH || process.env.CHROME_BIN;
  const chrome = executablePath ? { executablePath } : { channel: /** @type {const} */ ('chrome') };
  const browser = await puppeteer.launch({ ...chrome, headless: true, args: LAUNCH_ARGS });
  const rows = [];
  try {
    const page = await browser.newPage();
    for (const p of PAGES) {
      for (const width of WIDTHS) {
        await page.setViewport({ width, height: 800 });
        await page.goto(`${base}${p.path}`, { waitUntil: 'load' });
        await page.evaluate(() => document.fonts.ready);
        rows.push({ ...p, width, ...(await page.evaluate(measure)) });
      }
    }
  } finally {
    await browser.close();
    server.close();
  }
  const found = rows.flatMap(problems);
  if (!check) {
    const doc = replaceSection(await readFile(DOC, 'utf8'), DOC, MARK_START, MARK_END, renderSection(rows));
    await emit([[DOC, doc]], { check: false, rerun: 'npm run build && node scripts/design/header-fit.mjs' });
  }
  for (const p of found) console.error(p);
  console.log(`${PAGES.length} pages × ${WIDTHS.length} widths measured, ${found.length} problems`);
  if (found.length) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
