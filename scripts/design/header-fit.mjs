// Header width check for the site header (M4-04, #23), the follow-up to the M3-01 wireframe
// measurement (docs/design/nav-fit.md; its script went with the wireframes): can the real
// SiteHeader, in its own font (Inter) and spacing tokens, hold the en and vi first-level labels in
// one row from the narrowest desktop width (--bp-lg-up, 1024px) up?
// Serves dist/, opens the home page and, for each label set, rewrites the header labels in place,
// adds the language menu (not rendered while zh-TW is the only locale) and compares the bar's
// natural width with the width it has. Regenerates the marked section of docs/design/nav-fit.md.
// Run after npm run build: node scripts/design/header-fit.mjs  (--check compares without writing)
// Chinese glyphs fall back to the installed CJK font, so --check is not part of npm run check.

import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import puppeteer from 'puppeteer-core';
import { emit, replaceSection } from '../ia/generated.mjs';
import { serve } from '../lib/static-server.mjs';

const DIST = 'dist';
const DOC = 'docs/design/nav-fit.md';
const MARK_START = '<!-- generated by scripts/design/header-fit.mjs: start -->';
const MARK_END = '<!-- generated by scripts/design/header-fit.mjs: end -->';
// The narrowest width with the desktop menu (--bp-lg-up) and the common desktop width
export const WIDTHS = [1024, 1280];

// Measurement fixtures, not translations (menu copy is M7): the labels of nav-fit.md's wireframe
// measurement, first-level items in header order. null keeps the page's own zh-TW labels.
const en = { items: ['Products', 'Industries', 'Services', 'Resources', 'Company'], locale: 'English', contact: 'Contact Us' };
const vi = { items: ['Sản Phẩm', 'Giải pháp ngành', 'Dịch Vụ', 'Nguồn', 'Công Ty'], locale: 'Tiếng Việt', contact: 'Liên Hệ' };
export const SETS = [
  { id: 'zh-TW', labels: null },
  { id: 'en', labels: en },
  { id: 'en-long', labels: { ...en, items: en.items.with(1, 'Industry Solutions') } },
  { id: 'vi', labels: vi },
  { id: 'vi-long', labels: { ...vi, items: vi.items.with(1, 'Giải pháp theo ngành') } },
];

export const fits = ({ content, available }) => content <= available;

export function renderSection(rows) {
  const out = [MARK_START, '', '| 標籤組 | 視窗寬度 | 需要寬度 | 可用寬度 | 餘裕 | 放得下 |', '|---|--:|--:|--:|--:|---|'];
  for (const r of rows) out.push(`| \`${r.set}\` | ${r.width} | ${r.content} | ${r.available} | ${r.available - r.content} | ${fits(r) ? '✅' : '❌'} |`);
  out.push('', '寬度單位為 CSS px。需要寬度是 header 列不換行、不壓縮時的內容寬度（logo 到「聯絡我們」）；可用寬度是列扣掉左右留白。', '');
  out.push('標籤：', '');
  for (const r of rows.filter((r) => r.width === WIDTHS[0])) out.push(`- \`${r.set}\`：${r.labels.join('｜')}`);
  out.push('', MARK_END);
  return out.join('\n');
}

// Runs in the page: puts one label set into the desktop header and measures it
function measure(labels) {
  const header = document.querySelector('header.site-header');
  const bar = header.querySelector('.bar');
  const tools = bar.querySelector('.tools');
  const summaries = [...bar.querySelectorAll('.desktop-nav .top > li > details > summary')];
  const cta = tools.querySelector('.cta');
  // The language menu as SiteHeader renders it when a second locale exists; same scoped-style id
  if (!tools.querySelector('.locale')) {
    const scope = [...cta.attributes].find((a) => a.name.startsWith('data-astro-cid'));
    const locale = document.createElement('details');
    locale.className = 'locale';
    locale.innerHTML = '<summary><svg viewBox="0 0 24 24"></svg><span class="sr-only">語言：</span>中文</summary>';
    for (const el of [locale, ...locale.querySelectorAll('*')]) if (scope) el.setAttribute(scope.name, '');
    tools.insertBefore(locale, cta);
  }
  const localeLabel = tools.querySelector('.locale summary');
  const textNode = (el) => [...el.childNodes].find((n) => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
  if (labels) {
    summaries.forEach((s, i) => (textNode(s).textContent = labels.items[i]));
    textNode(localeLabel).textContent = labels.locale;
    cta.querySelector('a').textContent = labels.contact;
  }
  const style = getComputedStyle(bar);
  const available = Math.floor(bar.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight));
  bar.style.inlineSize = 'max-content';
  bar.style.maxInlineSize = 'none';
  const content = Math.ceil(bar.getBoundingClientRect().width - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight));
  return {
    labels: [...summaries, localeLabel, cta].map((el) => textNode(el.querySelector('a') ?? el).textContent.trim()),
    content,
    available,
  };
}

async function main() {
  if (!existsSync(join(DIST, 'index.html'))) throw new Error('dist/index.html not found; run npm run build first');
  const server = await serve(join(process.cwd(), DIST));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH, headless: true, args: ['--no-sandbox'] });
  const rows = [];
  try {
    const page = await browser.newPage();
    for (const set of SETS) {
      for (const width of WIDTHS) {
        await page.setViewport({ width, height: 800 });
        await page.goto(`${base}/`, { waitUntil: 'load' });
        await page.evaluate(() => document.fonts.ready);
        rows.push({ set: set.id, width, ...(await page.evaluate(measure, set.labels)) });
      }
    }
  } finally {
    await browser.close();
    server.close();
  }
  const doc = replaceSection(await readFile(DOC, 'utf8'), DOC, MARK_START, MARK_END, renderSection(rows));
  const stale = await emit([[DOC, doc]], { check: process.argv.includes('--check'), rerun: 'npm run build && node scripts/design/header-fit.mjs' });
  console.log(`${rows.length} rows measured, ${rows.filter((r) => !fits(r)).length} do not fit`);
  if (stale.length) process.exit(1);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
