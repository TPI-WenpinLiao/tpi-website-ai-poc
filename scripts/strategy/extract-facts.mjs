#!/usr/bin/env node
// Builds the fact library docs/strategy/facts.yaml from scripts/strategy/facts-source.yaml (#164).
// Which sentence of the current site is a fact is a judgment, so the selection is the input file
// (what was picked, verbatim); this script checks every pick against the live page and writes the
// library, so facts.yaml is never edited by hand (.claude/skills/site-research「事實庫」).
//
//   1. every fact's quote must be on its source page (HTML text, or the Nuxt chunks it loads);
//      one missing quote fails the run and nothing is written
//   2. facts.yaml is written in the input's order, groups as comments; a re-run gives the same file
//   3. docs/strategy/facts-candidates.md lists, for every zh-TW page in scope, the text blocks that
//      look like facts (numbers, certifications, awards, client names) and whether a fact or an
//      `ignore` rule covers them, so nothing is left out unnoticed
//
// Usage: node scripts/strategy/extract-facts.mjs [--offline] [--locales zh-TW,en]
//   --offline  read pages only from .cache/facts (filled by a previous online run)
//   --locales  verify only the facts of these locales (e.g. when www.tpisoftware.vn is unreachable);
//              the others are written unchanged and listed as not verified
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { parse, stringify } from 'yaml';
import { squash } from '../lib/page-text.mjs';
import { readCsv } from '../inventory/csv.mjs';
import { validateFacts } from './facts.mjs';
import { pageReader, textBlocks } from './source-pages.mjs';

export const SOURCE_FILE = 'scripts/strategy/facts-source.yaml';
const FACTS_FILE = 'docs/strategy/facts.yaml';
const REPORT_FILE = 'docs/strategy/facts-candidates.md';
const INVENTORY = 'docs/research/inventory.csv';

// The pages facts are taken from (issue #164: products, solutions, services, cases, about us)
export const SCOPE_TYPES = ['home', 'about', 'product-index', 'product', 'solution', 'service', 'case-study'];

const HEADER = `# Fact library (#163, #164). GENERATED by scripts/strategy/extract-facts.mjs from
# scripts/strategy/facts-source.yaml: do not edit here, change the source file and re-run.
# Every fact on a page (number, client, certification, award, product feature, case result,
# company data) is one entry here, traced to the current site.
# Pages use a fact with \`fact('<id>')\` (src/data/*.ts) or \`facts: [<id>]\` (Markdown frontmatter);
# everything else on a page is wording and may be original. Format and checks:
# \`node scripts/strategy/facts.mjs\` (offline, in \`npm run check\`) and
# \`node scripts/strategy/facts.mjs --sources\` (fetches every source.url, finds source.quote).
#
#   id      unique, lowercase letters, digits and \`-\`; en and vi entries end in \`-en\`, \`-vi\`
#   type    metric | client | certification | award | feature | case | company
#   text    the wording a page shows; may add U+200B break points or trim the quote
#   source  url: the current-site page; quote: the verbatim excerpt on that page
#   locale  zh-TW | en | vi (a page only uses facts in its own locale)
#   status  confirmed | to_confirm (pages only use confirmed facts)
#   note    optional; required for to_confirm: why (license, possibly outdated, locales disagree)
`;

/**
 * Facts of the source file, group defaults (url, locale) applied, `text` defaulting to the quote and
 * `status` to confirmed, in file order; each keeps the comment lines to write above it
 * @param {{ groups: Array<{ group: string, url?: string, locale?: string, comment?: string, facts: any[] }> }} source
 */
export function expand(source) {
  return source.groups.flatMap((g) =>
    g.facts.map((f, i) => {
      const { comment, quote, url, ...rest } = f;
      const fact = {
        id: rest.id,
        type: rest.type,
        text: rest.text ?? quote,
        source: { url: url ?? g.url, quote },
        locale: rest.locale ?? g.locale,
        status: rest.status ?? 'confirmed',
        ...(rest.note ? { note: rest.note } : {}),
      };
      const extra = Object.keys(rest).filter((k) => !['id', 'type', 'text', 'locale', 'status', 'note'].includes(k));
      if (extra.length) throw new Error(`${SOURCE_FILE} ${rest.id}: unknown field ${extra.join(', ')}`);
      const comments = [...(i === 0 ? [`--- ${g.group} ---`, ...(g.comment ? [g.comment] : [])] : []), ...(comment ? [comment] : [])];
      return { fact, comments };
    }),
  );
}

/** facts.yaml: the header, then every fact with its comments, one blank line between entries */
export function render(entries) {
  const body = entries.map(({ fact, comments }) => {
    const yaml = stringify([fact], { lineWidth: 0 }).trimEnd();
    return [...comments.map((c) => `# ${c}`), yaml].join('\n');
  });
  return `${HEADER}\n${body.join('\n\n')}\n`;
}

// What makes a text block look like a fact
const FACT_LIKE = /\d|ISO|CMMI|認證|專利|獎|榮獲|入選|殊榮|第一|唯一|首家|客戶|銀行|保險|人壽|產險|證券|金控|政府|醫院|集團/;

/**
 * Candidate rows of one page: fact-like blocks (at least 4 characters, not on most pages), deduped,
 * each with the facts or ignore rule that covers it. Facts from this page come first; a block only
 * facts from other pages cover is marked `elsewhere`, since that fact may say something else
 * @param {string[]} blocks
 * @param {{ id: string, quote: string, url: string }[]} facts
 * @param {{ match: RegExp, reason: string }[]} ignore
 * @param {Set<string>} common blocks on so many pages that they are site chrome
 * @param {string} url the page the blocks are from
 */
export function candidates(blocks, facts, ignore, common, url) {
  const seen = new Set();
  const rows = [];
  for (const b of blocks) {
    const key = squash(b);
    if (key.length < 4 || seen.has(key) || common.has(key) || !FACT_LIKE.test(b)) continue;
    seen.add(key);
    const covering = facts.filter((f) => key.includes(squash(f.quote)) || squash(f.quote).includes(key));
    const here = covering.filter((f) => f.url === url);
    const ids = (here.length ? here : covering).map((f) => f.id);
    const elsewhere = !here.length && covering.length > 0;
    const rule = ids.length ? undefined : ignore.find((r) => r.match.test(b));
    rows.push({ block: b, ids, elsewhere, reason: rule?.reason });
  }
  return rows;
}

const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

async function main() {
  const { values } = parseArgs({ options: { offline: { type: 'boolean' }, locales: { type: 'string' } } });
  const source = parse(await readFile(SOURCE_FILE, 'utf8'));
  const entries = expand(source);
  const facts = entries.map((e) => e.fact);
  const errors = validateFacts(facts);
  if (errors.length) throw new Error(errors.join('\n'));

  const reader = await pageReader({ offline: values.offline });
  const verify = values.locales ? new Set(values.locales.split(',')) : undefined;
  const missing = [];
  const unverified = [];
  for (const f of facts) {
    if (verify && !verify.has(f.locale)) unverified.push(f.id);
    else if (!(await reader.has(f.source.url, f.source.quote))) missing.push(`${f.id}: "${f.source.quote}" is not on ${f.source.url}`);
  }
  if (missing.length) throw new Error(`quotes not found, ${FACTS_FILE} not written:\n${missing.join('\n')}`);
  await writeFile(FACTS_FILE, render(entries));

  // Candidates on the zh-TW pages in scope (the page a redirect lands on, once)
  const rows = await readCsv(INVENTORY);
  const urls = [...new Set(rows.filter((r) => r.locale === 'zh-TW' && r.status === '200' && SCOPE_TYPES.includes(r.page_type)).map((r) => r.final_url))].sort();
  const pages = await Promise.all(urls.map(async (url) => ({ url, blocks: textBlocks(await reader.html(url)) })));
  const counts = new Map();
  for (const p of pages) for (const k of new Set(p.blocks.map(squash))) counts.set(k, (counts.get(k) ?? 0) + 1);
  const common = new Set([...counts].filter(([, n]) => n >= Math.max(3, pages.length / 3)).map(([k]) => k));
  const ignore = (source.ignore ?? []).map((r) => ({ match: new RegExp(r.match), reason: r.reason }));
  const zh = facts.filter((f) => f.locale === 'zh-TW').map((f) => ({ id: f.id, quote: f.source.quote, url: f.source.url }));

  let open = 0;
  let covered = 0;
  let skipped = 0;
  let elsewhere = 0;
  const sections = pages.map((p) => {
    const list = candidates(p.blocks, zh, ignore, common, p.url);
    for (const r of list) r.ids.length ? covered++ : r.reason ? skipped++ : open++;
    elsewhere += list.filter((r) => r.elsewhere).length;
    const ids = (r) => `${r.ids.map((id) => `\`${id}\``).join(' ')}${r.elsewhere ? '（他頁）' : ''}`;
    const table = list.map((r) => `| ${cell(r.block)} | ${r.ids.length ? ids(r) : r.reason ? `略過：${r.reason}` : '**未收**'} |`);
    return [`## ${p.url}`, '', ...(table.length ? ['| 段落 | 狀態 |', '|---|---|', ...table] : ['沒有像事實的段落。']), ''].join('\n');
  });
  const report = [
    '# 事實候選（自動產生）',
    '',
    `由 \`scripts/strategy/extract-facts.mjs\` 產生，不要手改。範圍是 \`${INVENTORY}\` 中 zh-TW、HTTP 200、類型為 ${SCOPE_TYPES.map((t) => `\`${t}\``).join('、')} 的頁面（轉址的取最終網址），共 ${pages.length} 頁。`,
    '',
    '每頁列出含數字、認證、獎項、客戶與產業名稱等字樣的文字區塊（出現在三分之一以上頁面的視為選單與 footer，不列），以及收進事實庫的 id，或 `facts-source.yaml` 的 `ignore` 規則寫的略過原因。「（他頁）」表示這頁沒有涵蓋它的事實，只有別頁來源的事實文字相符，那筆事實講的可能是別的產品，要人工確認。「**未收**」是還沒判斷的區塊。「已收」只表示有事實的原文在這個區塊裡，不表示區塊裡的每一項事實都收了：區塊比原文長、或有原文沒有的數字時，要看同頁其他列是否另外收了。',
    '',
    `合計：已收 ${covered}（其中他頁 ${elsewhere}）、略過 ${skipped}、未收 ${open}。`,
    '',
    ...sections,
  ].join('\n');
  await writeFile(REPORT_FILE, report);

  const byType = Object.entries(Object.groupBy(facts, (f) => `${f.locale} ${f.type}`)).map(([k, v]) => `${k}: ${v.length}`);
  console.log(`${FACTS_FILE}: ${facts.length} facts (${facts.filter((f) => f.status === 'confirmed').length} confirmed)\n  ${byType.join('\n  ')}`);
  if (unverified.length) console.log(`not verified (locale not in --locales): ${unverified.join(', ')}`);
  console.log(`${REPORT_FILE}: ${pages.length} pages, ${covered} covered (${elsewhere} by other pages' facts), ${skipped} ignored, ${open} open`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
